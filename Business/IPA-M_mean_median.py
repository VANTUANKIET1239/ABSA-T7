"""Compare IPA cutoffs from the canonical saved scores, without refitting models.

Only two CSVs are written. The selected mean/median figure is generated by
paper_figures/scripts/fig10_ipa_sensitivity.py.
"""
from pathlib import Path
import pandas as pd

if __package__:
    from . import ipa_shap_cleanser as pipeline
else:
    import ipa_shap_cleanser as pipeline

OUTPUT_DIR = Path(__file__).resolve().parent / 'customer_satisfaction_xai_ipa_mean_median_results_cleanser'
QUADRANTS = ['Concentrate Here', 'Keep Up the Good Work', 'Low Priority', 'Possible Overkill', 'Insufficient Data']


def compare_cutoffs(ipa):
    valid = ipa.Importance_Pct.notna() & ipa.Performance_0_100.notna()
    keys = ['Aspect', 'Importance_Pct', 'Performance_0_100', 'N_Performance_Valid', 'N_Mixed_Excluded']
    comparison = ipa[keys].copy()
    thresholds = []
    for method in ['mean', 'median']:
        importance = float(getattr(ipa.loc[valid, 'Importance_Pct'], method)())
        performance = float(getattr(ipa.loc[valid, 'Performance_0_100'], method)())
        quadrant = [pipeline.quadrant_of(row.Importance_Pct, row.Performance_0_100, importance, performance)
                    for row in ipa.itertuples()]
        comparison[f'IPA_Quadrant_{method.title()}'] = quadrant
        comparison[f'Importance_Cut_{method.title()}'] = importance
        comparison[f'Performance_Cut_{method.title()}'] = performance
        counts = pd.Series(quadrant).value_counts()
        thresholds.append({'Cut_Method': method, 'Importance_Cut': importance, 'Performance_Cut': performance,
                           'N_Aspects': len(ipa), **{q: int(counts.get(q, 0)) for q in QUADRANTS}})
    comparison['Quadrant_Changed'] = comparison.IPA_Quadrant_Mean.ne(comparison.IPA_Quadrant_Median)
    return comparison, pd.DataFrame(thresholds)


def main():
    ipa = pd.read_csv(pipeline.OUTPUT_DIR / 'ipa_attributes.csv', encoding='utf-8-sig')
    comparison, thresholds = compare_cutoffs(ipa)
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    comparison.to_csv(OUTPUT_DIR / 'ipa_mean_median_comparison.csv', index=False, encoding='utf-8-sig')
    thresholds.to_csv(OUTPUT_DIR / 'ipa_mean_median_thresholds.csv', index=False, encoding='utf-8-sig')
    print(thresholds.to_string(index=False))
    print(f'Changed quadrants: {int(comparison.Quadrant_Changed.sum())}/{len(comparison)}')


if __name__ == '__main__':
    main()
